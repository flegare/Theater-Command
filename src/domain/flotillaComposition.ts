export function getUnitBaseStats(classIniRef: string): {
  fundsCost: number;
  productionCost: number;
  pointValue: number;
  introducedYear: number;
  subCategory: FlotillaSubCategory;
  modernizationFamily?: string | undefined;
  modernizationLevel?: number | undefined;
  modernizationDescription?: string | undefined;
} {
  const asset = AVAILABLE_VANILLA_ASSETS.find(
    (a) => a.classIniRef === classIniRef,
  );
  if (asset) {
    return {
      fundsCost: asset.fundsCost,
      productionCost: asset.productionCost,
      pointValue: asset.pointValue,
      introducedYear: asset.introducedYear,
      subCategory: asset.subCategory,
      modernizationFamily: asset.modernizationFamily,
      modernizationLevel: asset.modernizationLevel,
      modernizationDescription: asset.modernizationDescription,
    };
  }

  // Fallback heuristics for uncatalogued or custom units
  if (classIniRef.startsWith("usn_cv") || classIniRef.startsWith("wp_cv")) {
    return {
      fundsCost: 400,
      productionCost: 75,
      pointValue: 15,
      introducedYear: 1975,
      subCategory: "aircraft_carrier",
    };
  }
  if (
    classIniRef.startsWith("usn_cg") ||
    classIniRef.startsWith("wp_rkr") ||
    classIniRef.startsWith("wp_bpk_kara")
  ) {
    return {
      fundsCost: 180,
      productionCost: 35,
      pointValue: 8,
      introducedYear: 1975,
      subCategory: "cruiser_battleship",
    };
  }
  if (
    classIniRef.startsWith("usn_dd") ||
    classIniRef.startsWith("wp_em") ||
    classIniRef.startsWith("wp_bpk")
  ) {
    return {
      fundsCost: 110,
      productionCost: 20,
      pointValue: 5,
      introducedYear: 1975,
      subCategory: "destroyer",
    };
  }
  if (
    classIniRef.startsWith("usn_ff") ||
    classIniRef.startsWith("wp_skr") ||
    classIniRef.startsWith("wp_mpk")
  ) {
    return {
      fundsCost: 65,
      productionCost: 12,
      pointValue: 3,
      introducedYear: 1972,
      subCategory: "frigate_corvette",
    };
  }
  if (classIniRef.startsWith("usn_ss") || classIniRef.startsWith("wp_ss")) {
    return {
      fundsCost: 120,
      productionCost: 22,
      pointValue: 5,
      introducedYear: 1975,
      subCategory: "attack_submarine_nuclear",
    };
  }
  if (
    classIniRef.includes("fighter") ||
    classIniRef.includes("f-") ||
    classIniRef.includes("mig-")
  ) {
    return {
      fundsCost: 35,
      productionCost: 5,
      pointValue: 10,
      introducedYear: 1975,
      subCategory: "fighter_interceptor",
    };
  }
  if (
    classIniRef.includes("bomber") ||
    classIniRef.includes("a-") ||
    classIniRef.includes("su-") ||
    classIniRef.includes("tu-")
  ) {
    return {
      fundsCost: 35,
      productionCost: 5,
      pointValue: 10,
      introducedYear: 1975,
      subCategory: "strike_attack_bomber",
    };
  }
  return {
    fundsCost: 25,
    productionCost: 4,
    pointValue: 3,
    introducedYear: 1970,
    subCategory: "mechanized_infantry",
  };
}

export function calculateCompositionCost(units: FlotillaUnit[]): {
  totalFunds: number;
  totalProduction: number;
  totalPoints: number;
} {
  let totalFunds = 0;
  let totalProduction = 0;
  let totalPoints = 0;

  for (const unit of units) {
    const stats = getUnitBaseStats(unit.classIniRef);
    const unitFunds = unit.fundsCost ?? stats.fundsCost;
    const unitProd = unit.productionCost ?? stats.productionCost;
    const unitPts = unit.pointValue ?? stats.pointValue;

    totalFunds += unitFunds * unit.count;
    totalProduction += unitProd * unit.count;
    totalPoints += unitPts * unit.count;
  }

  return { totalFunds, totalProduction, totalPoints };
}

export function filterAssetsByTimeline(
  assets: AvailableAssetCatalogItem[],
  currentYear: number,
  strictTimeline: boolean,
): AvailableAssetCatalogItem[] {
  if (!strictTimeline) {
    return assets;
  }
  return assets.filter((asset) => asset.introducedYear <= currentYear);
}

export function getAvailableModernizations(
  classIniRef: string,
  currentYear?: number,
  strictTimeline: boolean = false,
): AvailableAssetCatalogItem[] {
  const currentAsset = AVAILABLE_VANILLA_ASSETS.find(
    (a) => a.classIniRef === classIniRef,
  );
  if (!currentAsset || !currentAsset.modernizationFamily) {
    return [];
  }

  let familyVariants = AVAILABLE_VANILLA_ASSETS.filter(
    (a) => a.modernizationFamily === currentAsset.modernizationFamily,
  );

  if (strictTimeline && currentYear) {
    familyVariants = familyVariants.filter(
      (a) => a.introducedYear <= currentYear,
    );
  }

  // Sort by modernization level or introduced year
  return familyVariants.sort(
    (a, b) => (a.modernizationLevel ?? 0) - (b.modernizationLevel ?? 0),
  );
}

