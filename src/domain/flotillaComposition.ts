// -------------------------------------------------------------------------
// DYNAMIC TOTALS RECALCULATION
// -------------------------------------------------------------------------

export function recalculateCompositionTotals(units: FlotillaUnit[]): {
  totalVessels: number;
  totalSubmarines: number;
  totalAircraft: number;
  totalVehicles: number;
} {
  let totalVessels = 0;
  let totalSubmarines = 0;
  let totalAircraft = 0;
  let totalVehicles = 0;

  for (const unit of units) {
    if (unit.category === "vessel") {
      totalVessels += unit.count;
    } else if (unit.category === "submarine") {
      totalSubmarines += unit.count;
    } else if (unit.category === "aircraft") {
      totalAircraft += unit.count;
    } else if (unit.category === "land_unit") {
      totalVehicles += unit.count;
    }
  }

  return { totalVessels, totalSubmarines, totalAircraft, totalVehicles };
}

